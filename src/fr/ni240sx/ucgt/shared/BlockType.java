    private final int key;

    BlockType(int key){
    	this(key, true);
    }
    BlockType(int key, boolean reverse) {
        if (reverse) this.key = Integer.reverseBytes(key);
        else this.key = key;
    }

    public int getKey() {
        return key;
    }

    public String getName() {
        return name();
    }

    public static BlockType get(int key) {
        for (BlockType c : values()) {
            if (c.key == key) return c;
        }
        return INVALID; // Handle invalid value
    }
    
    
    
    
